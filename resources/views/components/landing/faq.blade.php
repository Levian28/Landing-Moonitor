    <div class="moon-faq-list">
        <details class="moon-faq-item">
            <summary>Bagaimana cara kerja MOONITOR?</summary>
            <p>Sensor membaca kondisi lingkungan kandang. Informasi tersebut ditampilkan melalui dashboard agar mudah dipantau.</p>
        </details>
        <details class="moon-faq-item">
            <summary>Informasi apa saja yang dapat dipantau?</summary>
            <p>Peternak dapat melihat suhu, kelembapan, kadar amonia, hidrogen sulfida, dan status kondisi kandang.</p>
        </details>
        <details class="moon-faq-item">
            <summary>Apakah tersedia riwayat kondisi kandang?</summary>
            <p>Ya. Riwayat pembacaan sensor dapat dilihat kembali untuk membantu mengetahui perubahan kondisi kandang.</p>
        </details>
        <details class="moon-faq-item">
            <summary>Apakah MOONITOR mudah digunakan oleh orang awam?</summary>
            <p>Tampilan MOONITOR dibuat sederhana agar informasi kondisi kandang mudah dipahami.</p>
        </details>
        <details class="moon-faq-item">
            <summary>Apakah MOONITOR dapat menggantikan pemeriksaan langsung?</summary>
            <p>Tidak. MOONITOR membantu memantau kondisi kandang, tetapi pemeriksaan langsung oleh peternak tetap diperlukan.</p>
        </details>
